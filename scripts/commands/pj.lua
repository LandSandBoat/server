local function error(player, msg)
    player:printToPlayer(msg)
    player:printToPlayer(MSG_USAGE)
end

local function normalizeName(name)
    return string.lower(name or '')
end

commandObj.onTrigger = function(player, targetName, forceZone)
    if not targetName or targetName == '' then
        error(player, MSG_INPUT_NAME)
        return
    end

    if forceZone then
        if forceZone ~= 0 and forceZone ~= 1 then
            error(player, MSG_FORCE_ZONE)
            return
        end
    else
        forceZone = 1
    end

    local party = player:getParty()
    if not party or #party <= 1 then
        error(player, MSG_NOT_IN_PARTY)
        return
    end

    local want = normalizeName(targetName)
    local targ = nil

    for _, member in ipairs(party) do
        if member and member:isPC() and normalizeName(member:getName()) == want then
            targ = member
            break
        end
    end

    if not targ then
        error(player, string.format(MSG_MEMBER_NOT_FOUND_FMT, targetName))
        return
    end

    -- If they're in mog house, goto them instead of setPos (matches !goto behavior).
    if not targ:inMogHouse() then
        player:setPos(
            targ:getXPos(),
            targ:getYPos(),
            targ:getZPos(),
            targ:getRotPos(),
            forceZone == 1 and targ:getZoneID() or nil
        )
    elseif not player:gotoPlayer(targ:getName()) then
        error(player, string.format(MSG_MOVE_FAILED_FMT, targ:getName()))
    end
end

return commandObj
