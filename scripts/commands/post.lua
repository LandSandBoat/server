-----------------------------------
-- func: post
-- desc: どこでもポスト有効時に宅配メニュー（受取/送信）を開く
-----------------------------------
---@type TCommand
local commandObj = {}

commandObj.cmdprops =
{
    permission = 0,
    parameters = 's'
}

-- クライアント側の文字化け対策として Shift_JIS バイト列を直接埋め込む
local MSG_USAGE_DETAIL = string.char(
    0x72, 0x65, 0x63, 0x76, 0x3A, 0x20, 0x8E, 0xF3, 0x8E, 0xE6, 0x89, 0xE6, 0x96, 0xCA, 0x82, 0xF0, 0x8A, 0x4A, 0x82, 0xAD, 0x20, 0x2F, 0x20, 0x73, 0x65, 0x6E, 0x64, 0x3A, 0x20, 0x91, 0x97, 0x95, 0x74, 0x89, 0xE6, 0x96, 0xCA, 0x82, 0xF0, 0x8A, 0x4A, 0x82, 0xAD
)
local MSG_DISABLED = string.char(
    0x82, 0xC7, 0x82, 0xB1, 0x82, 0xC5, 0x82, 0xE0, 0x83, 0x7C, 0x83, 0x58, 0x83, 0x67, 0x82, 0xAA, 0x96, 0xB3, 0x8C, 0xF8, 0x82, 0xC5, 0x82, 0xB7, 0x81, 0x42
)
local MSG_INVALID_MODE = string.char(
    0x70, 0x6F, 0x73, 0x74, 0x88, 0xF8, 0x90, 0x94, 0x82, 0xAA, 0x95, 0x73, 0x90, 0xB3, 0x82, 0xC5, 0x82, 0xB7, 0x81, 0x42
)

local function printUsage(player)
    player:printToPlayer('!post [recv|send]')
    player:printToPlayer(MSG_USAGE_DETAIL)
end

commandObj.onTrigger = function(player, mode)
    -- 運用設定が有効なときのみ、どこでも宅配メニューを開く。
    if not (xi.settings and xi.settings.map and xi.settings.map.POST_ENABLED_ANYWHERE) then
        player:printToPlayer(MSG_DISABLED)
        return
    end

    local m = string.lower(tostring(mode or 'recv'))
    if m == 'recv' then
        player:openRecvBox()
    elseif m == 'send' then
        player:openSendBox()
    else
        player:printToPlayer(MSG_INVALID_MODE)
        printUsage(player)
    end
end

return commandObj
