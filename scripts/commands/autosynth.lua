local function yesNoJa(flag)
    if flag then
        return MSG_YES
    end
    return MSG_NO
end

local function itemNameJa(itemId)
    if xi ~= nil and xi.synth_result_id_to_name_cp932 ~= nil and xi.synth_result_id_to_name_cp932[itemId] ~= nil then
        return xi.synth_result_id_to_name_cp932[itemId]
    end

    return string.format('%s(%u)', MSG_UNKNOWN_ITEM, itemId)
end

local function error(player, msg)
    player:printToPlayer(MSG_PREFIX .. ': ' .. msg)
    player:printToPlayer(MSG_USAGE)
end

local function resolveItemId(player, raw)
    local asNumber = tonumber(raw)
    if asNumber ~= nil then
        return asNumber
    end

    if xi ~= nil and xi.jpItemNameToId ~= nil then
        local jp = xi.jpItemNameToId[tostring(raw)]
        if type(jp) == 'number' then
            return jp
        elseif type(jp) == 'table' then
            player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_JP_AMBIG)
            for _, itemId in ipairs(jp) do
                player:printToPlayer(string.format('  - itemId=%u', itemId))
            end
            return nil
        end
    end

    if xi ~= nil and xi.synth_result_names_cp932 ~= nil then
        local cp932Match = xi.synth_result_names_cp932[tostring(raw)]
        if type(cp932Match) == 'number' then
            return cp932Match
        elseif type(cp932Match) == 'table' then
            player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_JP_AMBIG)
            for _, itemId in ipairs(cp932Match) do
                player:printToPlayer(string.format('  - itemId=%u', itemId))
            end
            return nil
        end
    end

    local retItem = GetItemIDByName(tostring(raw))
    if retItem > 0 and retItem < 65000 then
        return retItem
    elseif retItem >= 65000 then
        player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_EN_AMBIG)
        return nil
    end

    player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_ITEM_NOT_FOUND)
    return nil
end

local function buildRequiredItems(recipe)
    local required = {}
    local order = {}

    local function addRequired(itemId, quantity)
        if itemId == nil or itemId <= 0 or quantity <= 0 then
            return
        end

        if required[itemId] == nil then
            required[itemId] = quantity
            table.insert(order, itemId)
        else
            required[itemId] = required[itemId] + quantity
        end
    end

    addRequired(recipe.crystal, 1)
    for _, ingredientId in ipairs(recipe.ingredients) do
        addRequired(ingredientId, 1)
    end

    return required, order
end

local function getInventoryCounts(player)
    local inventoryCounts = {}

    for _, item in ipairs(player:getItems()) do
        local itemId = item:getID()
        local quantity = item:getQuantity() or 0
        inventoryCounts[itemId] = (inventoryCounts[itemId] or 0) + quantity
    end

    return inventoryCounts
end

local function countNeededSlots(required, inventoryCounts)
    local neededSlots = 0

    for itemId, quantity in pairs(required) do
        local owned = inventoryCounts[itemId] or 0
        if owned < quantity then
            neededSlots = neededSlots + 1
        end
    end

    return neededSlots
end

local function printRecipeCandidates(player, recipes)
    player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_MULTI_RECIPE)
    for _, recipe in ipairs(recipes) do
        player:printToPlayer(
            string.format(
                '  - recipe_id=%u %s%s %s%u %s%u %s%s',
                recipe.recipe_id,
                MSG_SKILL_TYPE,
                skillNameJa(recipe.skill),
                MSG_SKILL_LEVEL,
                recipe.skill_level or 0,
                MSG_INGREDIENT_COUNT,
                #(recipe.required_items or {}),
                MSG_NPC_ONLY,
                yesNoJa(recipe.npc_buyable_only)
            )
        )
    end
    player:printToPlayer(MSG_RECIPE_SELECT_HINT)
end

local function joinParts(parts)
    if #parts == 0 then
        return ''
    end

    return table.concat(parts, ' / ')
end

local function printRecipePreview(player, itemId, recipe)
    player:printToPlayer(
        string.format(
            '%s itemId=%u recipe_id=%u %s%s %s%u %s%s',
            MSG_RECIPE_PREVIEW,
            itemId,
            recipe.recipe_id,
            MSG_SKILL_TYPE,
            skillNameJa(recipe.skill),
            MSG_SKILL_LEVEL,
            recipe.skill_level or 0,
            MSG_NPC_ONLY,
            yesNoJa(recipe.npc_buyable_only)
        )
    )
    local materialParts = {}
    local npcParts = {}
    for _, entry in ipairs(recipe.required_items or {}) do
        table.insert(
            materialParts,
            string.format('%s x%u', itemNameJa(entry.item_id), entry.quantity or 0)
        )
        table.insert(
            npcParts,
            string.format('%s=%s', itemNameJa(entry.item_id), yesNoJa(entry.npc_buyable))
        )
    end

    if #materialParts > 0 then
        player:printToPlayer(MSG_MATERIALS .. ' ' .. joinParts(materialParts))
        player:printToPlayer(MSG_NPC_BUYABLE_LIST .. ' ' .. joinParts(npcParts))
    end
end

local function selectRecipeById(recipes, recipeId)
    for _, recipe in ipairs(recipes) do
        if recipe.recipe_id == recipeId then
            return recipe
        end
    end
    return nil
end

local function grantRequiredItems(player, required, order)
    local ID = zones[player:getZoneID()]

    for _, itemId in ipairs(order) do
        local quantity = required[itemId]
        local obtained = player:addItem(itemId, quantity)

        if not obtained then
            player:printToPlayer(string.format('%s %u x%u', MSG_GRANT_FAILED, itemId, quantity))
            return false
        end

        if quantity > 1 then
            player:messageSpecial(ID.text.ITEM_OBTAINED + 9, itemId, quantity)
        else
            player:messageSpecial(ID.text.ITEM_OBTAINED, itemId)
        end
    end

    return true
end

commandObj.onTrigger = function(player, arg, arg2, arg3)
    if arg == nil or tostring(arg) == '' then
        error(player, MSG_ITEM_NOT_FOUND)
        return
    end

    if not xi.synth_recipes then
        player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_NOT_LOADED)
        return
    end

    local itemId = resolveItemId(player, arg)
    if itemId == nil or itemId <= 0 then
        return
    end

    local recipes = xi.synth_recipes[itemId]
    if recipes == nil then
        player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_RECIPE_NOT_FOUND)
        return
    end

    local recipe = nil
    local confirmArg = nil

    if #recipes == 1 then
        recipe = recipes[1]
        confirmArg = arg2
    else
        if arg2 == nil or tostring(arg2) == '' then
            printRecipeCandidates(player, recipes)
            return
        end

        local recipeId = tonumber(arg2)
        if recipeId == nil or recipeId <= 0 then
            player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_RECIPE_ID_INVALID)
            return
        end

        recipe = selectRecipeById(recipes, recipeId)
        if recipe == nil then
            player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_RECIPE_ID_NOT_FOUND)
            printRecipeCandidates(player, recipes)
            return
        end

        confirmArg = arg3
    end

    printRecipePreview(player, itemId, recipe)

    if confirmArg == nil or tostring(confirmArg) == '' then
        return
    end

    if tostring(confirmArg) ~= '1' then
        player:printToPlayer(MSG_PREFIX .. ': ' .. MSG_CONFIRM_INVALID)
        return
    end

    local required, order = buildRequiredItems(recipe)
    local inventoryCounts = getInventoryCounts(player)
    local neededSlots = countNeededSlots(required, inventoryCounts)
    local freeSlots = player:getFreeSlotsCount()

    if neededSlots > freeSlots then
        player:printToPlayer(string.format('%s: %s%u/%u', MSG_PREFIX, MSG_NOT_ENOUGH_SLOTS, neededSlots, freeSlots))
        return
    end

    if not grantRequiredItems(player, required, order) then
        return
    end

    player:printToPlayer(
        string.format(
            '%s %s%s %s%u recipe_id=%u itemId=%u',
            MSG_GRANTED,
            MSG_SKILL_TYPE,
            skillNameJa(recipe.skill),
            MSG_SKILL_LEVEL,
            recipe.skill_level or 0,
            recipe.recipe_id,
            itemId
        )
    )
    player:printToPlayer(MSG_GRANTED_DETAIL)
end

return commandObj
