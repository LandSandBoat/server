entity.onMobInitialize = function(mob)
    mob:setMobMod(xi.mobMod.DONT_ROAM_HOME, 1)
    mob:setMobMod(xi.mobMod.DETECTION, xi.detects.SIGHT)
    mob:setTrueDetection(true)
end

entity.onMobSpawn = function(mob)
    mob:setRoamFlags(xi.roamFlag.SCRIPTED)
    mob:setBaseSpeed(45)
    mob:setLocalVar('pathPoint', 1)
end

entity.onMobRoam = function(mob)
    entity.onMobRoamAction(mob)
end

entity.onMobFight = function(mob, target)
    if mob:checkDistance(target) > 40 then
        mob:disengage()
        mob:resetEnmity()
    end
end

entity.onMobDisengage = function(mob)
    entity.onMobRoamAction(mob)
end

entity.onMobDeath = function(mob, player, isKiller)
end

entity.onMobRoamAction = function(mob)
    local dahakOffset = mob:getID() - 17035324
    local pathStart = patrolPath[dahakOffset][1]
    local pathEnd = patrolPath[dahakOffset][#patrolPath[dahakOffset]]
    local pathPoint = mob:getLocalVar('pathPoint')

    if mob:atPoint(pathStart) then
        mob:setLocalVar('pathDirection', 1)
    elseif mob:atPoint(pathEnd) then
        mob:setLocalVar('pathDirection', 2)
    end

    if mob:atPoint(patrolPath[dahakOffset][pathPoint]) then
        if mob:getLocalVar('pathDirection') == 1 then
            if pathPoint > 10 and pathPoint < 30 and math.random() <= 0.05 then
                mob:setLocalVar('pathPoint', pathPoint - 1)
            else
                mob:setLocalVar('pathPoint', pathPoint + 1)
            end
        elseif mob:getLocalVar('pathDirection') == 2 then
            if pathPoint > 10 and pathPoint < 30 and math.random() <= 0.05 then
                mob:setLocalVar('pathPoint', pathPoint + 1)
            else
                mob:setLocalVar('pathPoint', pathPoint - 1)
            end
        end
    end

    local targetPoint = patrolPath[dahakOffset][pathPoint]

    mob:pathTo(targetPoint[1], targetPoint[2], targetPoint[3])
end

return entity
