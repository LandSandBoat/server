---@type TMobEntity
local entity = {}

entity.onMobSpawn = function(mob)
    xi.goblinBountyHunter.onMobSpawn(mob)
end

entity.onMobRoamAction = function(mob)
    xi.goblinBountyHunter.patrol(mob, routes[mob:getID()])
end

entity.onMobDisengage = function(mob)
    xi.goblinBountyHunter.patrol(mob, routes[mob:getID()])
end

entity.onMobDeath = function(mob, player, optParams)
    xi.regime.checkRegime(player, mob, 97, 2, xi.regime.type.FIELDS)
    xi.regime.checkRegime(player, mob, 98, 2, xi.regime.type.FIELDS)

    if
        xi.settings.main.ENABLE_ACP == 1 and
        not player:hasKeyItem(xi.keyItem.CHUNK_OF_SMOKED_GOBLIN_GRUB) and
        player:getCurrentMission(xi.mission.log_id.ACP) >= xi.mission.id.acp.THE_ECHO_AWAKENS
    then
        -- Guesstimating 15% chance
        if math.randomInt(1, 100) <= 15 then
            npcUtil.giveKeyItem(player, xi.keyItem.CHUNK_OF_SMOKED_GOBLIN_GRUB)
        end
    end
end

return entity
