-- Data rows hold HP and MP in columns 1 and 2, which are not part of this test yet
local firstStatColumn = 3

local function compareStats(actual, expected, description)
    local statNames = { 'STR', 'DEX', 'VIT', 'AGI', 'INT', 'MND', 'CHR' }
    local hasDiff = false

    -- Check if there are any differences
    for i = 1, #statNames do
        if actual[i] ~= expected[i + firstStatColumn - 1] then
            hasDiff = true
            break
        end
    end

    if hasDiff then
        local expStr = {}
        local actStr = {}
        for j = 1, #statNames do
            local expectedStat = expected[j + firstStatColumn - 1]
            if actual[j] ~= expectedStat then -- Only add stats that differ
                table.insert(expStr, string.format('%s:%d', statNames[j], expectedStat))
                table.insert(actStr, string.format('%s:%d', statNames[j], actual[j]))
            end
        end

        return false, string.format('\n%s\nExpected: %s\nActual:   %s',
            description,
            table.concat(expStr, ' '),
            table.concat(actStr, ' '))
    end

    return true
end

